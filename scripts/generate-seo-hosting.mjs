import { readFile, writeFile } from 'node:fs/promises';
import { migrationRoutes } from './seo-routing.mjs';
const path = new URL('../vercel.json', import.meta.url);
let current = {};
try { current = JSON.parse(await readFile(path, 'utf8')); }
catch (error) { if (error.code !== 'ENOENT') throw error; }
// Never silently replace routing rules introduced outside this generator.
const marker = 'ReeCell SEO migration: generated by scripts/generate-seo-hosting.mjs';
if (Object.keys(current).length && current.$comment !== marker && JSON.stringify(current.routes) !== JSON.stringify(migrationRoutes())) throw new Error('Configuração Vercel existente: integrar suas regras manualmente antes de gerar.');
const { $comment, ...preserved } = current;
const config = { ...preserved, $schema: 'https://openapi.vercel.sh/vercel.json', framework: 'astro', buildCommand: 'npm run build && npm run verify && npm run verify:seo', outputDirectory: 'dist', routes: migrationRoutes() };
await writeFile(path, JSON.stringify(config, null, 2) + '\n');
console.log(`${config.routes.length} regras Vercel preparadas. Nenhum deploy ou vínculo de domínio realizado.`);
